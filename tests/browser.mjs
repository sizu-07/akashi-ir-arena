import {createRequire} from 'node:module';
import {mkdirSync,mkdtempSync,rmSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createApp} from '../apps/server/main.mjs';

const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const dir=mkdtempSync(path.join(os.tmpdir(),'arena-browser-'));
const output='artifacts/browser';
mkdirSync(output,{recursive:true});
const config={httpPort:0,mqttPort:0,operatorPin:'12345678',devices:[1,2,3,4].map(n=>({id:`gun-00${n}`,key:`test-${n}`,name:`プレイヤー${n}`,shooterId:n}))};
const app=await createApp({config,demo:true,dataDir:dir,bind:'127.0.0.1'});
const base=`http://127.0.0.1:${app.httpServer.address().port}`;
let browser;
const errors=[];
try{
  browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1280,height:800},hasTouch:true});
  const admin=await context.newPage();
  const display=await context.newPage();
  admin.on('dialog',dialog=>dialog.accept());
  for(const page of [admin,display])page.on('pageerror',error=>errors.push(error.message));
  await admin.goto(base);
  await admin.locator('#pin').fill(config.operatorPin);
  await admin.getByRole('button',{name:'ログイン',exact:true}).click();
  await admin.locator('#dashboard').waitFor({state:'visible'});
  await admin.locator('[data-action=start]').waitFor({state:'visible'});
  await admin.waitForFunction(()=>!document.querySelector('[data-action=start]').disabled);
  await admin.locator('[data-action=start]').click();
  await admin.locator('#operationAlert').waitFor({state:'visible'});
  assert.match(await admin.locator('#operationAlertText').innerText(),/投影画面/);
  assert.match(await admin.locator('#operationAlertNext').innerText(),/表示を準備/);
  await display.goto(`${base}/display`);
  await display.locator('#prepare').click();
  await admin.waitForFunction(()=>document.getElementById('readiness').textContent.includes('準備完了')&&document.getElementById('readiness').textContent.includes('4/4'));
  assert.equal(await admin.locator('#operationCenter').isVisible(),true);
  assert.match(await admin.locator('#operationTitle').innerText(),/仮想端末でのデモ待機中/);
  await admin.locator('[data-media=rules]').click();
  await display.waitForFunction(()=>document.getElementById('overlayTitle').textContent==='4人個人戦');
  await admin.locator('[data-media=score]').click();
  assert.equal(await display.locator('.player').count(),4);
  assert.equal(await display.locator('#round').textContent(),'1 / 4');
  assert.equal(await admin.locator('#roundLabel').textContent(),'第1ゲーム / 全4ゲーム');
  await admin.screenshot({path:`${output}/operator-ready.png`,fullPage:true});
  await display.screenshot({path:`${output}/projector-ready.png`});
  await admin.locator('[data-action=start]').click();
  await admin.waitForFunction(()=>document.getElementById('phase').textContent==='試合中',{timeout:10000});
  await admin.locator('[data-action=pause]').click();
  await admin.waitForFunction(()=>document.getElementById('phase').textContent==='一時停止');
  assert.match(await admin.locator('#operationTitle').innerText(),/運営が一時停止/);
  assert.match(await admin.locator('#operationNext').innerText(),/ゲームを再開/);
  await admin.locator('[data-action=start]').click();
  await admin.waitForFunction(()=>document.getElementById('phase').textContent==='試合中',{timeout:10000});
  await admin.locator('#demoShooter').selectOption('gun-001');
  await admin.locator('#demoVictim').selectOption('gun-002');
  await admin.locator('#demoReceiver').selectOption('all');
  await admin.locator('#demoHit').click();
  await admin.waitForFunction(()=>document.getElementById('score').textContent.includes('プレイヤー1 1'));
  assert.equal(app.game.player('gun-001').kills,1);
  assert.equal(app.game.player('gun-002').deaths,1);
  assert.equal(app.game.player('gun-002').hp,0);
  assert.equal(await display.locator('.is-out').count(),1);
  await admin.screenshot({path:`${output}/operator-kill.png`,fullPage:true});
  await display.screenshot({path:`${output}/projector-kill.png`});
  await display.waitForFunction(async()=>((await(await fetch('/api/state')).json()).players[1].hp===1),{timeout:8500});
  assert.equal(app.game.player('gun-001').kills,1);
  await admin.locator('#demoEndRound').click();
  await admin.waitForFunction(()=>document.getElementById('phase').textContent==='途中経過');
  await display.waitForFunction(()=>document.getElementById('overlayTitle').textContent==='途中経過');
  assert.match(await display.locator('#resultBoard .result-row').first().innerText(),/プレイヤー1[\s\S]*1/);
  assert.equal(await display.locator('#round').textContent(),'2 / 4');
  await display.screenshot({path:`${output}/intermission.png`});
  await admin.locator('[data-action=finish]').click();
  await admin.waitForFunction(()=>document.getElementById('phase').textContent==='試合終了');
  assert.equal(app.game.s.roundResults.length,1);
  assert.equal(app.game.s.winner,'gun-001');
  await admin.setViewportSize({width:768,height:1024});
  await admin.screenshot({path:`${output}/operator-tablet.png`,fullPage:true});
  assert.equal(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  writeFileSync(`${output}/result.json`,JSON.stringify({revision:'0.8',checkedAt:new Date().toISOString(),passed:true,checks:['individual rules slide','four-player ranking','one-hit kill','seven-second respawn','demo round skip','force match finish','tablet width'],errors},null,2));
  console.log('Browser E2E: PASS');
}finally{
  await browser?.close();
  await app.close();
  rmSync(dir,{recursive:true,force:true});
}
